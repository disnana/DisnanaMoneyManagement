"""Refresh the offline calendar after the Cabinet Office publishes new dates each February.

Run python3 scripts/update-japanese-holidays.py [downloaded-syukujitsu.csv].
"""

import argparse
import csv
from datetime import date, timedelta
import io
import json
from pathlib import Path
from urllib.request import urlopen


SOURCE = "https://www8.cao.go.jp/chosei/shukujitsu/syukujitsu.csv"
GUIDE = "https://www8.cao.go.jp/chosei/shukujitsu/gaiyou.html"
OUTPUT = Path(__file__).resolve().parents[1] / "packages/core/src/data/japaneseHolidayDates.ts"
DAY = timedelta(days=1)


def holiday_name(day, holidays):
    name = holidays[day]
    # The CSV groups these two days under 休日（祝日扱い）. Event names and dates:
    # https://www8.cao.go.jp/chosei/shukujitsu/sokuigaiyou.pdf
    if name == "休日（祝日扱い）":
        events = {date(2019, 5, 1): "天皇の即位の日", date(2019, 10, 22): "即位礼正殿の儀"}
        return events.get(day, name)
    if name != "休日":
        return name

    # Article 3(2). Before 2007, the substitute could only be the following day.
    previous = day - DAY
    while previous in holidays and holidays[previous] != "休日":
        if previous.weekday() == 6:
            return "振替休日"
        if day.year < 2007:
            break
        previous -= DAY

    # Article 3(3). Use only national holidays, including days legally treated as such.
    if all(neighbour in holidays and holidays[neighbour] != "休日" for neighbour in (day - DAY, day + DAY)):
        return "国民の休日"
    raise ValueError(f"Check the legal classification of {day} in the Cabinet Office guidance")


def generate(raw):
    rows = csv.reader(io.StringIO(raw.decode("cp932")))
    if next(rows) != ["国民の祝日・休日月日", "国民の祝日・休日名称"]:
        raise ValueError("Unexpected Cabinet Office CSV header")
    holidays = {}
    for raw_day, name in rows:
        day = date(*map(int, raw_day.split("/")))
        if day in holidays or not name:
            raise ValueError(f"Invalid holiday entry for {day}")
        holidays[day] = name

    first_year, last_year = min(holidays).year, max(holidays).year
    for year in range(first_year, last_year + 1):
        if date(year, 1, 1) not in holidays or date(year, 11, 23) not in holidays:
            raise ValueError(f"Incomplete Cabinet Office data for {year}")

    lines = [
        "// Generated by scripts/update-japanese-holidays.py. Do not edit by hand.",
        f"// 内閣府「国民の祝日について」 {GUIDE}",
        f"// {SOURCE} ({first_year}–{last_year}). 「休日」は祝日法第3条により区分。2019年の即位関連は行事名で表示。",
        "export const japaneseHolidayDates: Readonly<Partial<Record<string, string>>> = {",
    ]
    for day in sorted(holidays):
        name = json.dumps(holiday_name(day, holidays), ensure_ascii=False)
        lines.append(f'  "{day}": {name},')
    return "\n".join([*lines, "};", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("csv", nargs="?", type=Path)
    args = parser.parse_args()
    if args.csv:
        data = args.csv.read_bytes()
    else:
        with urlopen(SOURCE, timeout=30) as response:
            data = response.read()
    OUTPUT.write_bytes(generate(data).encode("utf-8"))
